# 7. Evaluate and Process All Leads
final_results = []

# Fallback check to ensure variable is defined
if 'optimized_classifier' not in globals():
    optimized_classifier = classifier

print("Running inference over full dataset...")
for _, row in tqdm(df.iterrows(), total=len(df), desc="Classifying"):
    try:
        res = optimized_classifier(lead_description=row["lead_description"])
        pred_priority = res.priority.lower().strip()
        final_results.append({
            "Predicted_Priority": pred_priority,
            "Reason": res.reason,
            "Confidence": res.confidence
        })
    except Exception as e:
        final_results.append({
            "Predicted_Priority": "review required",
            "Reason": str(e),
            "Confidence": None
        })

final_df = pd.concat([df, pd.DataFrame(final_results)], axis=1)

# Compute test accuracy
test_predictions = []
for _, r in test_df.iterrows():
    try:
        pred = optimized_classifier(lead_description=r["lead_description"]).priority.lower().strip()
        test_predictions.append(pred)
    except Exception:
        test_predictions.append("review required")

test_accuracy = accuracy_score(test_df["priority"], test_predictions)
print(f"\nClassifier Test Accuracy: {test_accuracy * 100:.2f}%")

# 8. Export Results
final_df.to_csv("DSPy_Classified_Leads_Final.csv", index=False)
final_df.to_excel("DSPy_Classified_Leads_Final.xlsx", index=False)
