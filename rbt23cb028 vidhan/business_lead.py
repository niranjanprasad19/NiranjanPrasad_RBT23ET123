# 2. Import libraries and request Gemini API Key
import dspy
import pandas as pd
import numpy as np
from sklearn.model_selection import train_test_split
from sklearn.metrics import accuracy_score, classification_report
from tqdm.notebook import tqdm
from google.colab import files
from getpass import getpass

try:
    google_api_key = getpass("Enter your Google AI Studio API Key: ")
except NameError:
    pass

# 3. Load and Split Dataset
print("Please upload 'leads_dataset_120.csv' if prompted:")
uploaded = files.upload()
FILE_NAME = "leads_dataset_120.csv"
if FILE_NAME not in uploaded:
    raise FileNotFoundError(f"Please upload the file named {FILE_NAME}")

df = pd.read_csv(FILE_NAME, encoding="utf-8-sig")
df["lead_description"] = df["lead_description"].fillna("").astype(str).str.strip()
df["priority"] = df["priority"].astype(str).str.strip().str.lower()
df = df[(df["lead_description"] != "") & (df["priority"].isin(["high", "medium", "low"]))].reset_index(drop=True)

train_df, test_df = train_test_split(df, test_size=0.33, random_state=42, stratify=df["priority"])
print(f"Dataset loaded successfully: {len(train_df)} training leads, {len(test_df)} testing leads.")

# 4. Configure DSPy with Gemini 1.5 Flash using the correct model namespace
try:
    lm = dspy.LM(model="gemini/models/gemini-1.5-flash", api_key=google_api_key, temperature=0)
except AttributeError:
    lm = dspy.GoogleModel(model="models/gemini-1.5-flash", api_key=google_api_key, temperature=0)

dspy.configure(lm=lm)
print("DSPy successfully configured with Google Gemini 1.5 Flash!")

# 5. Define DSPy Signature and Predictor
from typing import Literal

class LeadClassification(dspy.Signature):
    """
    Classify business leads based on descriptions into:
    HIGH: Strong buying intent, budget, immediate urgency.
    MEDIUM: Mild interest, needs follow-up or nurturing.
    LOW: Casual inquiry, no clear requirement or unlikely conversion.
    """
    lead_description: str = dspy.InputField(desc="Business lead description")
    priority: Literal["high", "medium", "low"] = dspy.OutputField(desc="Predicted lead priority")
    reason: str = dspy.OutputField(desc="Explanation for classification")
    confidence: float = dspy.OutputField(desc="Confidence score between 0 and 1")

classifier = dspy.Predict(LeadClassification)

# 6. Optimize Classifier with Few-Shot Bootstrapping
trainset = [
    dspy.Example(lead_description=row["lead_description"], priority=row["priority"]).with_inputs("lead_description")
    for _, row in train_df.iterrows()
]

def classification_metric(example, prediction, trace=None):
    return example.priority.lower().strip() == prediction.priority.lower().strip()

optimizer = dspy.BootstrapFewShot(
    metric=classification_metric,
    max_bootstrapped_demos=2,
    max_labeled_demos=4,
    max_rounds=1
)

print("Optimizing classifier using DSPy...")
try:
    optimized_classifier = optimizer.compile(student=classifier, trainset=trainset)
except Exception as e:
    print(f"Optimization failed ({e}). Falling back to unoptimized classifier.")
    optimized_classifier = classifier

print("Optimization complete!")

